import pandas as pd
import numpy as np
import matplotlib.pyplot as plt
import seaborn as sns

sns.set_theme(style="whitegrid")

print("E-COMMERCE SALES DATA ANALYSIS")
print("All libraries imported successfully!")

import os

file_path = "Ecommerce_Sales_Data.csv"

if not os.path.exists(file_path):
    file_path = "/content/Ecommerce_Sales_Data.csv"

if not os.path.exists(file_path):
    file_path = "/Ecommerce_Sales_Data.csv"

df = pd.read_csv(file_path)

print("Dataset loaded successfully!")
print("Number of rows:", df.shape[0])
print("Number of columns:", df.shape[1])

display(df.head())

print("=" * 60)
print("DATASET OVERVIEW")
print("=" * 60)

print("\nColumn Names:")
print(df.columns.tolist())

print("\nDataset Information:")
df.info()

print("\nStatistical Summary:")
display(df.describe().round(2))

print("\nMissing Values:")
display(df.isnull().sum().to_frame("Missing Values"))

print("=" * 60)
print("DATA CLEANING AND PREPROCESSING")
print("=" * 60)

# Check duplicate records
print("Duplicate rows before cleaning:", df.duplicated().sum())

# Remove duplicate records
df = df.drop_duplicates().copy()

# Convert columns to correct data types
df["Order Date"] = pd.to_datetime(
    df["Order Date"], errors="coerce"
)

numeric_columns = [
    "Unit Price", "Quantity", "Discount", "Sales", "Profit"
]

for col in numeric_columns:
    df[col] = pd.to_numeric(df[col], errors="coerce")

# Remove rows missing essential information
df = df.dropna(
    subset=["Order Date", "Sales", "Profit", "Category"]
).copy()

# Create useful date columns
df["Year"] = df["Order Date"].dt.year
df["Month"] = df["Order Date"].dt.month
df["Month_Name"] = df["Order Date"].dt.strftime("%b")
df["Year_Month"] = df["Order Date"].dt.to_period("M").astype(str)

# Calculate profit margin
df["Profit_Margin"] = np.where(
    df["Sales"] != 0,
    (df["Profit"] / df["Sales"]) * 100,
    np.nan
)

print("\nDuplicate rows after cleaning:", df.duplicated().sum())
print("Dataset shape after cleaning:", df.shape)

print("\nCleaned dataset preview:")
display(df.head())

print("\nMissing values after cleaning:")
display(df.isnull().sum().to_frame("Missing Values"))

print("=" * 60)
print("KEY BUSINESS METRICS")
print("=" * 60)

total_sales = df["Sales"].sum()
total_profit = df["Profit"].sum()
total_quantity = df["Quantity"].sum()
total_orders = df["Order ID"].nunique()
total_products = df["Product Name"].nunique()

profit_margin = (
    total_profit / total_sales * 100
    if total_sales != 0 else 0
)

print(f"Total Sales: ${total_sales:,.2f}")
print(f"Total Profit: ${total_profit:,.2f}")
print(f"Total Quantity Sold: {total_quantity:,}")
print(f"Total Orders: {total_orders:,}")
print(f"Unique Products: {total_products:,}")
print(f"Overall Profit Margin: {profit_margin:.2f}%")

print("\nSales Statistics:")
display(df["Sales"].describe().to_frame().round(2))

print("\nProfit Statistics:")
display(df["Profit"].describe().to_frame().round(2))

category_analysis = df.groupby("Category").agg(
    Total_Sales=("Sales", "sum"),
    Total_Profit=("Profit", "sum"),
    Quantity_Sold=("Quantity", "sum")
)

category_analysis["Profit_Margin_%"] = (
    category_analysis["Total_Profit"]
    / category_analysis["Total_Sales"] * 100
)

category_analysis = category_analysis.sort_values(
    "Total_Sales", ascending=False
)

print("CATEGORY-WISE SALES AND PROFIT")
display(category_analysis.round(2))

# Sales chart
plt.figure(figsize=(9, 5))

sns.barplot(
    data=category_analysis.reset_index(),
    x="Category",
    y="Total_Sales"
)

plt.title("Total Sales by Product Category")
plt.xlabel("Product Category")
plt.ylabel("Total Sales (USD)")
plt.tight_layout()
plt.show()

# Profit chart
plt.figure(figsize=(9, 5))

sns.barplot(
    data=category_analysis.reset_index(),
    x="Category",
    y="Total_Profit"
)

plt.title("Total Profit by Product Category")
plt.xlabel("Product Category")
plt.ylabel("Total Profit (USD)")
plt.tight_layout()
plt.show()

monthly_analysis = (
    df.set_index("Order Date")
    .resample("MS")
    .agg({
        "Sales": "sum",
        "Profit": "sum"
    })
)

monthly_analysis.columns = [
    "Total_Sales", "Total_Profit"
]

print("MONTHLY SALES ANALYSIS")
display(monthly_analysis.round(2))

plt.figure(figsize=(12, 5))

plt.plot(
    monthly_analysis.index,
    monthly_analysis["Total_Sales"],
    marker="o"
)

plt.title("Monthly Sales Trend")
plt.xlabel("Month")
plt.ylabel("Total Sales (USD)")
plt.xticks(rotation=45)
plt.tight_layout()
plt.show()

plt.figure(figsize=(12, 5))

plt.plot(
    monthly_analysis.index,
    monthly_analysis["Total_Profit"],
    marker="o"
)

plt.title("Monthly Profit Trend")
plt.xlabel("Month")
plt.ylabel("Total Profit (USD)")
plt.xticks(rotation=45)
plt.tight_layout()
plt.show()

product_analysis = df.groupby("Product Name").agg(
    Total_Sales=("Sales", "sum"),
    Total_Profit=("Profit", "sum"),
    Quantity_Sold=("Quantity", "sum")
)

top_products = product_analysis.sort_values(
    "Total_Sales", ascending=False
).head(10)

print("TOP 10 PRODUCTS BY SALES")
display(top_products.round(2))

plt.figure(figsize=(10, 6))

sns.barplot(
    data=top_products.reset_index().sort_values("Total_Sales"),
    x="Total_Sales",
    y="Product Name"
)

plt.title("Top 10 Products by Sales")
plt.xlabel("Total Sales (USD)")
plt.ylabel("Product Name")
plt.tight_layout()
plt.show()

# CORRELATION HEATMAP

correlation_columns = [
    "Sales",
    "Profit",
    "Quantity",
    "Discount",
    "Profit_Margin"
]

correlation_matrix = df[correlation_columns].corr()

print("CORRELATION MATRIX")
display(correlation_matrix.round(2))

plt.figure(figsize=(10, 7))

sns.heatmap(
    correlation_matrix,
    annot=True,
    fmt=".2f",
    cmap="coolwarm",
    vmin=-1,
    vmax=1,
    linewidths=0.5
)

plt.title("Correlation Heatmap of E-Commerce Sales", fontsize=15)
plt.tight_layout()
plt.show()

# SCATTER PLOT: DISCOUNT VS PROFIT

plt.figure(figsize=(10, 6))

sns.scatterplot(
    data=df,
    x="Discount",
    y="Profit",
    hue="Category",
    alpha=0.75,
    s=65
)

plt.title("Discount vs Profit by Product Category", fontsize=15)
plt.xlabel("Discount Rate")
plt.ylabel("Profit (USD)")
plt.legend(title="Category")
plt.tight_layout()
plt.show()

# BOX PLOT: PROFIT BY CATEGORY

plt.figure(figsize=(10, 6))

sns.boxplot(
    data=df,
    x="Category",
    y="Profit",
    hue="Category",
    legend=False
)

plt.title("Profit Distribution by Product Category", fontsize=15)
plt.xlabel("Product Category")
plt.ylabel("Profit (USD)")
plt.tight_layout()
plt.show()

# BOX PLOT: SALES DISTRIBUTION

plt.figure(figsize=(9, 5))

sns.boxplot(
    data=df,
    x="Sales"
)

plt.title("Distribution of E-Commerce Sales", fontsize=15)
plt.xlabel("Sales (USD)")
plt.tight_layout()
plt.show()

# E-COMMERCE SALES DATA ANALYSIS DASHBOARD

fig, axes = plt.subplots(3, 3, figsize=(22, 16))

# 1. Monthly Sales Trend
axes[0, 0].plot(
    monthly_analysis.index,
    monthly_analysis["Total_Sales"],
    marker="o"
)
axes[0, 0].set_title("Monthly Sales Trend")
axes[0, 0].tick_params(axis="x", rotation=45)

# 2. Sales by Category
category_analysis["Total_Sales"].plot(
    kind="bar", ax=axes[0, 1]
)
axes[0, 1].set_title("Sales by Category")
axes[0, 1].tick_params(axis="x", rotation=20)

# 3. Top 10 Products
top_products["Total_Sales"].sort_values().plot(
    kind="barh", ax=axes[0, 2]
)
axes[0, 2].set_title("Top 10 Products by Sales")

# 4. Sales by Region
region_sales = df.groupby("Region")["Sales"].sum().sort_values()
region_sales.plot(kind="bar", ax=axes[1, 0])
axes[1, 0].set_title("Sales by Region")
axes[1, 0].tick_params(axis="x", rotation=0)

# 5. Sales by Customer Segment
segment_sales = df.groupby("Segment")["Sales"].sum()
axes[1, 1].pie(
    segment_sales,
    labels=segment_sales.index,
    autopct="%1.1f%%",
    startangle=90
)
axes[1, 1].set_title("Sales by Customer Segment")

# 6. Discount vs Profit
sns.scatterplot(
    data=df,
    x="Discount",
    y="Profit",
    hue="Category",
    alpha=0.6,
    ax=axes[1, 2],
    legend=False
)
axes[1, 2].set_title("Discount vs Profit")

# 7. Correlation Heatmap
sns.heatmap(
    correlation_matrix,
    annot=True,
    fmt=".2f",
    cmap="coolwarm",
    vmin=-1,
    vmax=1,
    ax=axes[2, 0]
)
axes[2, 0].set_title("Correlation Heatmap")

# 8. Sales Distribution
sns.histplot(
    data=df,
    x="Sales",
    bins=25,
    kde=True,
    ax=axes[2, 1]
)
axes[2, 1].set_title("Sales Distribution")

# 9. Profit by Category
sns.boxplot(
    data=df,
    x="Category",
    y="Profit",
    hue="Category",
    legend=False,
    ax=axes[2, 2]
)
axes[2, 2].set_title("Profit Distribution by Category")
axes[2, 2].tick_params(axis="x", rotation=20)

# Main title and layout
fig.suptitle(
    "E-COMMERCE SALES DATA ANALYSIS DASHBOARD",
    fontsize=21,
    fontweight="bold"
)

plt.tight_layout(rect=[0, 0, 1, 0.96])

